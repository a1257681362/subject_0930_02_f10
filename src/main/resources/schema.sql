-- aqua-4 疫病观察与隔离池调度
-- 发现异常症状生成观察单（风险等级+观察人），按风险等级推荐隔离池；
-- 转移前校验池容量、消毒状态、目标池调入权限，调度失败说明冲突原因；
-- 隔离中批次禁止混养与出池，解除隔离必须兽医复核；
-- 原池与隔离池之间数量变化逐笔记录；定时复查任务幂等生成，操作者不丢。
