-- ============================================================
-- aqua-10 养殖成本分摊与批次结转
-- 关键口径：
--   1) 饲料/人工/药品/能源四类费用按「池塘+批次」归集，人工补录必须引用财务凭证号；
--   2) 转池时按数量与生物量权重把未结成本分配到同池各养殖批次（50% 数量权重 + 50% 生物量权重，
